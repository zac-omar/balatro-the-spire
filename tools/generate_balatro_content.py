"""Generate Jimbo's StS2 content classes from your copy of Balatro.

Every Balatro joker, voucher, deck, stake, tarot, planet and spectral card becomes a Slay the
Spire 2 model: jokers, vouchers, decks and stakes are relics, consumables are potions. StS2
registers models by C# type, so each one needs a class. This script reads Balatro's item
definitions (game.lua inside Balatro.exe) and writes those classes, with each item's key, name
and sprite cell, to sts2-mod/BalatroBridge/Generated/BalatroContent.g.cs.

The file only holds keys, names and sprite positions; the text players read comes from the
running Balatro itself (the dealer's catalog). It is derived from Balatro, so it is gitignored:
the deploy script regenerates it before every build.

    python tools/generate_balatro_content.py [--balatro-dir games/Balatro]
"""
from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from build_balatro import split_fused_exe  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "sts2-mod" / "BalatroBridge" / "Generated" / "BalatroContent.g.cs"

# Balatro set -> (C# base class, class-name suffix, sprite sheet, cell size at 2x)
KINDS = {
    "Joker": ("JokerRelic", "", "Jokers", 142, 190),
    "Voucher": ("VoucherRelic", "Voucher", "Vouchers", 142, 190),
    "Back": ("DeckRelic", "", "Enhancers", 142, 190),
    "Stake": ("StakeRelic", "", "chips", 58, 58),
    "Tarot": ("TarotPotion", "Tarot", "Tarots", 142, 190),
    "Planet": ("PlanetPotion", "Planet", "Tarots", 142, 190),
    "Spectral": ("SpectralPotion", "Spectral", "Tarots", 142, 190),
}

# Decks that aren't real choices.
SKIP = {"b_challenge"}


@dataclass
class Item:
    key: str
    set: str
    name: str
    order: int
    col: int
    row: int
    rarity: int
    soul: tuple[int, int] | None
    cost: int

    @property
    def class_name(self) -> str:
        name = self.name
        if self.set == "Stake":
            name = name.replace("Chip", "Stake")
        words = re.findall(r"[A-Za-z0-9]+", name.replace("'", ""))
        pascal = "".join(w[:1].upper() + w[1:] for w in words)
        return "Balatro" + pascal + KINDS[self.set][1]


def field(body: str, name: str) -> str | None:
    m = re.search(rf"\b{name}\s*=\s*(\"[^\"]*\"|'[^']*'|[-\w.]+)", body)
    return m.group(1).strip("\"'") if m else None


def pos(body: str, name: str) -> tuple[int, int] | None:
    m = re.search(rf"\b{name}\s*=\s*\{{\s*x\s*=\s*(\d+)\s*,\s*y\s*=\s*(\d+)\s*\}}", body)
    return (int(m.group(1)), int(m.group(2))) if m else None


def parse(game_lua: str) -> list[Item]:
    items = []
    for line in game_lua.splitlines():
        m = re.match(r"\s*(\w+)\s*=\s*\{(.*)\}\s*,?\s*(--.*)?$", line)
        if not m:
            continue
        key, body = m.group(1), m.group(2)
        kind = field(body, "set")
        if kind not in KINDS or key in SKIP or not re.match(r"^(j|v|b|c|stake)_", key):
            continue
        cell = pos(body, "pos")
        name = field(body, "name")
        if cell is None or name is None:
            sys.exit(f"error: couldn't read {key}'s name or sprite from game.lua")
        items.append(Item(key, kind, name, int(field(body, "order") or 0), cell[0], cell[1],
                          int(field(body, "rarity") or 0), pos(body, "soul_pos"), int(field(body, "cost") or 0)))
    return items


def csharp(items: list[Item]) -> str:
    out = [
        "// <auto-generated>",
        "// Generated by tools/generate_balatro_content.py from your copy of Balatro. Don't edit or",
        "// commit it; the deploy script regenerates it.",
        "// </auto-generated>",
        "#nullable enable",
        "using BalatroBridge.Content;",
        "",
        "namespace BalatroBridge.Content",
        "{",
    ]
    for item in items:
        out.append(f"    public sealed class {item.class_name} : {KINDS[item.set][0]};")
    out += [
        "",
        "    internal static partial class BalatroContent",
        "    {",
        "        public static readonly BalatroItem[] All =",
        "        [",
    ]
    for item in items:
        sheet, w, h = KINDS[item.set][2:]
        soul = f"new(\"{sheet}\", {item.soul[0]}, {item.soul[1]}, {w}, {h})" if item.soul else "null"
        out.append(
            f"            new(typeof({item.class_name}), \"{item.key}\", \"{item.set}\", \"{item.name}\", {item.order}, "
            f"{item.rarity}, {item.cost}, new(\"{sheet}\", {item.col}, {item.row}, {w}, {h}), {soul}),")
    out += ["        ];", "    }", "}", ""]
    return "\n".join(out)


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate Jimbo's content classes from Balatro.")
    parser.add_argument("--balatro-dir", type=Path, default=ROOT / "games" / "Balatro",
                        help="folder containing the original Balatro.exe (default: games/Balatro)")
    parser.add_argument("--out", type=Path, default=OUT)
    args = parser.parse_args()

    exe = args.balatro_dir / "Balatro.exe"
    if not exe.is_file():
        sys.exit(f"error: {exe} not found")
    _, game = split_fused_exe(exe.read_bytes())
    items = parse(game.read("game.lua").decode("utf-8", errors="replace"))
    order = list(KINDS)
    items.sort(key=lambda i: (order.index(i.set), i.order, i.key))

    names: dict[str, str] = {}
    for item in items:
        if item.class_name in names:
            sys.exit(f"error: {item.key} and {names[item.class_name]} would both be {item.class_name}")
        names[item.class_name] = item.key
    counts = {kind: sum(1 for i in items if i.set == kind) for kind in KINDS}
    if counts["Joker"] < 100 or counts["Back"] < 10:
        sys.exit(f"error: only found {counts}; has game.lua's format changed?")

    args.out.parent.mkdir(parents=True, exist_ok=True)
    text = csharp(items)
    if not args.out.is_file() or args.out.read_text(encoding="utf-8") != text:
        args.out.write_text(text, encoding="utf-8")
    print(f"Generated {args.out.relative_to(ROOT)}: " + ", ".join(f"{n} {k.lower()}s" for k, n in counts.items()))


if __name__ == "__main__":
    main()
